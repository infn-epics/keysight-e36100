#!/usr/bin/env python3
"""A simulator of Keysight E36100B series DC power supply (E36103B 20 V / 2 A): answers, over TCP, the commands the IOC sends.

Generated by the ARGUS IOC engineer (ioc_scaffold_module) from the module's description.
It keeps one value per quantity: a query answers it, a setting changes it. Edit STATE or answer() to make it
behave more like the device (ramps, interlocks, errors).

    python3 sim/e36100_sim.py --port 5025
"""
import argparse
import re
import socketserver

TERMINATOR = b'\n'

STATE = {
    'Voltage': 0.0,
    'VoltageSet': 0.0,
    'Current': 0.0,
    'CurrentSet': 0.0,
    'OVP': 22.0,
    'Output': 0,
    'Ident': 'Keysight Technologies,E36103B,SIM00001,1.0',
    'Error': '+0,"No error"'
}

# query -> (quantity, reply format)
READS = {
    'MEAS:VOLT?': ('Voltage', '%f'),
    'VOLT?': ('Voltage', '%f'),
    'MEAS:CURR?': ('Current', '%f'),
    'CURR?': ('Current', '%f'),
    'VOLT:PROT?': ('OVP', '%f'),
    'OUTP?': ('Output', '%d'),
    '*IDN?': ('Ident', '%s'),
    'SYST:ERR?': ('Error', '%s')
}

# (command pattern, quantity, type, acknowledgement)
WRITES = [
    (re.compile('^VOLT\\ \\s*(\\S+?)$'), 'Voltage', float, None),
    (re.compile('^CURR\\ \\s*(\\S+?)$'), 'Current', float, None),
    (re.compile('^VOLT:PROT\\ \\s*(\\S+?)$'), 'OVP', float, None),
    (re.compile('^OUTP\\ \\s*(\\S+?)$'), 'Output', int, None)
]


def answer(line):
    """The device's reply to one command, or None when it sends none."""
    if line in READS:
        name, fmt = READS[line]
        return fmt % STATE[name]
    for pattern, name, kind, ack in WRITES:
        match = pattern.match(line)
        if match:
            try:
                STATE[name] = kind(float(match.group(1))) if kind is int else kind(match.group(1))
            except ValueError:
                return ack and "ERR"
            return ack
    print(f"unknown command {line!r}")
    return None


class Handler(socketserver.BaseRequestHandler):
    def handle(self):
        buffer = b""
        while True:
            data = self.request.recv(1024)
            if not data:
                return
            buffer += data
            while TERMINATOR in buffer:
                raw, buffer = buffer.split(TERMINATOR, 1)
                reply = answer(raw.decode(errors="replace").strip())
                if reply is not None:
                    self.request.sendall(reply.encode() + TERMINATOR)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=5025)
    args = parser.parse_args()
    socketserver.ThreadingTCPServer.allow_reuse_address = True
    with socketserver.ThreadingTCPServer((args.host, args.port), Handler) as server:
        print(f"e36100 simulator on {args.host}:{args.port}")
        server.serve_forever()


if __name__ == "__main__":
    main()
